// Find leaderboard scores whose rngSeed doesn't match the canonical
// board's rngSeed for that date. The canonical-board sync (~v1.5.27)
// guarantees every player on the same ET date plays the same layout,
// but a brief window before runStartupGate shipped (v1.5.31) allowed
// silent divergence on a Firebase cold-load race. This script flags
// any score that recorded an rngSeed different from the canonical's
// for that date — those scores are paired against the wrong feature
// vector in the R refit and should be dropped.
//
// Usage:
//   node scripts/audit-divergent-scores.mjs              # report only
//   node scripts/audit-divergent-scores.mjs --delete --only 2026-08-06/-Oz…
//                                                        # delete named rows
//
// A bare --delete is REFUSED: pass --only <date>/<pushId> per row. See the
// comment on `only` below for why the wide report and the narrow delete have
// to be different scopes.
//
// Read-only by default, and the READ half needs no credentials — daily/ and
// dailyBoard/ are world-readable.
//
// DELETION NEEDS THE SERVICE ACCOUNT, so --delete only works in Actions.
// This comment used to claim the opposite ("does NOT require authentication
// because daily/$date/$entry has public write rules"), and that was simply
// wrong — every delete it attempted came back 401 (found 2026-08-06). The
// live rule is
//     auth != null && !data.exists() && newData.child('uid').val() === auth.uid
// and a DELETE fails all three clauses at once: it carries no auth, the row
// by definition exists, and it has no newData to carry a uid. The
// !data.exists() clause makes these rows APPEND-ONLY — no client can delete
// one, not even the player who wrote it. Only the service account, which
// bypasses rules entirely, can. Deletion is irreversible; back the row up
// first.

import { tokenFromEnv } from './service-account-auth.mjs';

const DB_BASE = 'https://gregsweeper-66d02-default-rtdb.firebaseio.com';

async function fetchJson(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url} -> ${r.status}`);
  return r.json();
}

(async () => {
  const args = process.argv.slice(2);
  const doDelete = args.includes('--delete');
  // --only <date>/<pushId>, repeatable. Deletion is restricted to exactly
  // these rows; everything else is still REPORTED, never touched.
  //
  // This exists because a bare --delete is almost never what you want any
  // more (2026-08-06). The report legitimately lists 94 divergent rows, but
  // 92 of them predate CANONICAL_ERA_START: those boards were regenerated by
  // backfill-old-dailies.mjs, so their stored seed disagrees with the
  // canonical BY CONSTRUCTION and the rows are the real scores people played.
  // Deleting them would wipe most of the leaderboard's history to remove two
  // genuine divergences. The audit is a wide net on purpose; the delete has
  // to be a scalpel.
  const only = new Set();
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--only' && args[i + 1]) only.add(args[i + 1]);
  }
  if (doDelete && only.size === 0) {
    console.error('Refusing a blanket --delete: pass --only <date>/<pushId> for each row.');
    console.error('Run without --delete first and pick the rows deliberately.');
    process.exit(1);
  }

  console.log(`Audit divergent scores (${doDelete ? `DELETE MODE, ${only.size} target(s)` : 'report only'})`);
  console.log('');

  const [boards, daily] = await Promise.all([
    fetchJson(`${DB_BASE}/dailyBoard.json`),
    fetchJson(`${DB_BASE}/daily.json`),
  ]);

  if (!boards) { console.error('no canonical boards on Firebase'); process.exit(1); }
  if (!daily)  { console.log('no scores on Firebase — nothing to audit'); return; }

  const dates = Object.keys(daily).sort();
  let totalScores = 0;
  let auditableScores = 0;
  let divergentScores = 0;
  const divergentRows = [];

  for (const date of dates) {
    const scores = daily[date] || {};
    const board = boards[date];
    const canonicalSeed = board?.rngSeed || null;

    for (const [pushId, score] of Object.entries(scores)) {
      totalScores++;
      // Pre-canonical-system dates have no board record; skip.
      if (!canonicalSeed) continue;
      // Pre-rngSeed-tracking submissions don't carry the field. The
      // submitter omits it when seed === date (non-experiment day),
      // so a missing rngSeed means "scored against the date itself."
      const scoreSeed = score?.rngSeed || date;
      auditableScores++;
      if (scoreSeed !== canonicalSeed) {
        divergentScores++;
        divergentRows.push({
          date, pushId, name: score?.name || '?', uid: score?.uid || '?',
          time: score?.time, scoreSeed, canonicalSeed,
        });
      }
    }
  }

  console.log(`dates with canonical: ${Object.keys(boards).length}`);
  console.log(`total score rows: ${totalScores}`);
  console.log(`auditable rows (canonical exists): ${auditableScores}`);
  console.log(`divergent rows: ${divergentScores}`);
  console.log('');

  if (divergentRows.length === 0) {
    console.log('No divergent scores found.');
    return;
  }

  console.log('Divergent scores:');
  for (const row of divergentRows) {
    console.log(`  ${row.date} ${row.pushId}  ${row.name.padEnd(15)}  ${String(row.time).padStart(6)}s  ${row.scoreSeed} (expected ${row.canonicalSeed})`);
  }

  if (!doDelete) {
    console.log('');
    console.log('Re-run with --delete to remove these from Firebase.');
    return;
  }

  console.log('');
  console.log('Deleting…');
  const targeted = divergentRows.filter(r => only.has(`${r.date}/${r.pushId}`));
  const unmatched = [...only].filter(k => !targeted.some(r => `${r.date}/${r.pushId}` === k));
  if (unmatched.length) {
    console.error(`  no divergent row matches: ${unmatched.join(', ')}`);
    console.error('  (a row that is NOT divergent is never deletable through this tool)');
    process.exit(1);
  }
  // Rules forbid a client delete outright (see the header), so this half is
  // service-account-only and fails loudly rather than 401-ing per row.
  const token = await tokenFromEnv();
  for (const row of targeted) {
    const url = new URL(`${DB_BASE}/daily/${row.date}/${row.pushId}.json`);
    url.searchParams.set('access_token', token);
    const r = await fetch(url, { method: 'DELETE' });
    if (!r.ok) {
      console.error(`  FAILED  ${row.date}/${row.pushId}: ${r.status}`);
    } else {
      console.log(`  deleted ${row.date}/${row.pushId}`);
    }
  }
  console.log('Done.');
})().catch(err => {
  console.error(err.message);
  process.exit(1);
});
