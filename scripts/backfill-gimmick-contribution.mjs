// One-off (re-runnable) historical instrument for the gimmick-contribution
// study: computes the contribution features (`<g>Required` / `<g>ClicksSaved`
// — see boardSolver.computeContributionFeatures) plus the locked mine/number
// split for every stored canonical board, and writes them to a committed side
// file the R refit's SECONDARY contribution fit joins by date.
//
// Why a side file and not Firebase: dailyMeta is write-once, so historical
// rows can never gain the keys; and R cannot run the JS solver, so the
// canonical-era backlog has to be measured HERE (the
// scripts/extract-par-experiment.mjs precedent). Prospective boards carry the
// keys in dailyMeta from generation; the R join prefers the meta copy (the
// solver of record at generation time) and falls back to this file, which is
// a re-measure under TODAY'S solver — the backfit-model-history disclosure
// semantics.
//
// READ-ONLY against Firebase (world-readable paths, no secrets). Re-running
// refreshes the file — do so once after the 7-day precompute horizon rolls
// over, so the boards written before the feature shipped (whose write-once
// metas will never carry the keys) get their rows here.
//
// Coverage: dailyBoard/{date} for date >= CANONICAL_ERA_START (before that
// the stored board was regenerated by the backfill and is NOT the board the
// scores describe — the same provenance floor as DIGIT_ERA_START), and
// weeklyBoard/{weekStart} keyed `${weekStart}_weekly_first` to match the
// score rows' join key. Boards with no gimmicks still get a row (all zeros
// plus the locked split) so the fit's controls see a complete frame.
//
// Usage: node scripts/backfill-gimmick-contribution.mjs [--dry-run]

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { deserializeBoard } from '../src/firebase/dailyBoardSync.js';
import { computeContributionFeatures, isBoardSolvable } from '../src/logic/boardSolver.js';
import { cleanSolverArtifacts } from '../src/logic/boardGenerator.js';
import { CANONICAL_ERA_START } from '../src/logic/archiveEligibility.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DB_BASE = 'https://gregsweeper-66d02-default-rtdb.firebaseio.com';
const OUT_PATH = join(__dirname, 'data', 'gimmick-contribution.json');
const DRY_RUN = process.argv.includes('--dry-run');

async function dbGet(path) {
  const r = await fetch(`${DB_BASE}/${path}.json`);
  if (!r.ok) throw new Error(`GET ${path} -> ${r.status}`);
  return r.json();
}

function measureBoard(raw) {
  const d = deserializeBoard(raw);
  const { board, rows, cols } = d;
  const fr = Math.floor(d.firstClick / cols);
  const fc = d.firstClick % cols;
  // Same acceptance the sweep applies — an uncertified stored board gets no
  // row rather than a measurement of noise.
  const check = isBoardSolvable(board, rows, cols, fr, fc);
  cleanSolverArtifacts(board);
  if (!(check.solvable || check.remainingUnknowns === 0)) return null;

  const contribution = computeContributionFeatures(board, rows, cols, fr, fc, d.activeGimmicks);
  cleanSolverArtifacts(board);
  let lockedMineCount = 0;
  let lockedNumberCount = 0;
  for (const row of board) {
    for (const cell of row) {
      if (!cell.isLocked) continue;
      if (cell.isMine) lockedMineCount++;
      else lockedNumberCount++;
    }
  }
  return { gimmicks: d.activeGimmicks, ...contribution, lockedMineCount, lockedNumberCount };
}

console.log('fetching dailyBoard…');
const daily = await dbGet('dailyBoard');
console.log('fetching weeklyBoard…');
const weekly = await dbGet('weeklyBoard');

const rows = [];
const skipped = [];
for (const [date, raw] of Object.entries(daily || {})) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || date < CANONICAL_ERA_START) continue;
  try {
    const m = measureBoard(raw);
    if (m) rows.push({ date, ...m });
    else skipped.push(`${date} (uncertified)`);
  } catch (e) {
    skipped.push(`${date} (${e.message})`);
  }
}
for (const [weekStart, raw] of Object.entries(weekly || {})) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(weekStart) || weekStart < CANONICAL_ERA_START) continue;
  try {
    const m = measureBoard(raw);
    // The join key the weekly-first score rows land under in daily/.
    if (m) rows.push({ date: `${weekStart}_weekly_first`, ...m });
    else skipped.push(`${weekStart}_weekly_first (uncertified)`);
  } catch (e) {
    skipped.push(`${weekStart}_weekly_first (${e.message})`);
  }
}
rows.sort((a, b) => (a.date < b.date ? -1 : 1));

const out = {
  generatedAt: new Date().toISOString(),
  note: 'Historical contribution measure under the solver at generatedAt; '
    + 'dailyMeta-carried keys (generation-time solver of record) take precedence in the R join.',
  rows,
};

const withGimmicks = rows.filter((r) => r.gimmicks.length > 0).length;
console.log(`measured ${rows.length} boards (${withGimmicks} with gimmicks); skipped ${skipped.length}`);
if (skipped.length) console.log('  skipped:', skipped.join(', '));
if (DRY_RUN) {
  console.log('[dry-run] not writing', OUT_PATH);
} else {
  writeFileSync(OUT_PATH, JSON.stringify(out, null, 1) + '\n');
  console.log('wrote', OUT_PATH);
}
