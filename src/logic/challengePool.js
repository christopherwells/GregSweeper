// THE PROVEN POOL, every board spec the ladder and the endless zone draw
// from, measured offline by scripts/search-endless-specs.mjs through the ONE
// builder the play path uses (challenge250Builder), and re-proved by
// scripts/validate-challenge250-specs.mjs.
//
// It is a LEAF: this module imports nothing, so challenge250.js stays
// readable by UI surfaces and tests without pulling in the solver. It is
// data and only data, every decision about which entry a level gets lives
// in challenge250.js.
//
// WHY ONE POOL FOR BOTH CONSUMERS. Christopher's design (2026-08-08) has the
// ladder ramping difficulty over a widening band from L26 to L250 and the
// endless zone holding a hard floor with maximum variety past it. Those are
// two draws over one space, not two spaces: an endless-only pool floored at
// 3.5 s/cell (which is what the old search built) can serve neither the
// ladder's 0.55 opening nor its 2.15 middle.
//
// EVERY ENTRY STORES ITS MEASURED ppc, the median par-per-cell over the
// search's seeds, at the par model of the day it was measured. That number is
// what the ladder's band matches against and what the validator's acceptance
// band centers on, so a REFIT THAT MOVES A SHAPE'S EQUATION RE-PRICES THE
// POOL and the numbers here go stale. Re-run the search (or at least
// harden-endless-pool) after one, exactly as TILING_BAND_CONFIGS requires;
// the validator is not in CI and will not tell you on its own.
//
// `ppc` is the FIRST argument of E() so a sorted table reads as a difficulty
// ladder down the page.
//
// THE DEDUCTION-FLOOR PURGE (2026-08-12, issue #286). The braid stamps
// minDeductions on every level it assigns, and the search that filled these
// tables never asked a draw for a deduction count, so the pool held faces
// whose certified boards are too short a quarter of the time or worse: the
// validator refused draws on 16 assigned braid levels, four of which the
// issue had already named. Every LADDER + CHALLENGE face was measured under
// the floor (16 single-salt builds for the per-salt short rate, then 24
// builds under the play path's own three-salt contract), and 117 faces were
// removed: everything with a per-salt short rate of 25% or more, or any
// refused build in 24. Faces that miss a salt occasionally but never failed a real build
// stay, because the three salts exist to absorb exactly that. Replacements
// were proven under the same two readings before entering, and the search's
// acceptance now carries the floor (search-endless-specs.mjs), so a face of
// this class cannot be measured into the pool again. Rect was untouched:
// its builder retries the floor away inside one build.

/**
 * @param {number} ppc measured median par-per-cell
 * @param {object} spec
 * @param {number} [spread] maxPar/minPar over the face's own measurement, which
 *   sizes its validator band (ppcBandFor). Absent on entries that predate the
 *   spread capture, and absent reads as the flat band rather than a wide one.
 */
const E = (ppc, spec, spread) => Object.freeze({
  ...spec, ppc, gimmicks: Object.freeze(spec.gimmicks || []),
  ...(Number.isFinite(spread) ? { spread } : {}),
});
